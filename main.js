// РЕНДЕР КАТАЛОГУ
// =============================================
function renderCards(filter = "all") {
  const container = document.getElementById("catalog-container");
  container.innerHTML = "";

  const normalizedFilter = normalizeFilter(filter);
  const filtered = normalizedFilter === "all"
    ? catalog
    : catalog.filter(c => normalizeFilter(c.category) === normalizedFilter);

  filtered.forEach(item => {
    const priceHtml = item.price
      ? `<span class="price-value">${item.price} грн</span>`
      : `<span class="price-call">Ціна: уточнюйте по телефону</span>`;

    const card = document.createElement("div");
    card.className = "col-12 col-sm-6 col-lg-4 col-xl-3";
    card.innerHTML = `
      <div class="product-card" data-id="${item.id}" role="button" tabindex="0" aria-label="Деталі: ${item.name}">
        <div class="product-card__img-wrap">
          <img src="${item.image}" alt="${item.name}" class="product-card__img" loading="lazy"
               onerror="this.src='img/placeholder.jpg'; this.onerror=null;">
          <span class="product-card__badge">${categoryLabel(item.category)}</span>
        </div>
        <div class="product-card__body">
          <h3 class="product-card__title">${item.name}</h3>
          <p class="product-card__desc">${item.shortDesc}</p>
          <div class="product-card__price">${priceHtml}</div>
          <div class="product-card__actions">
            <a href="tel:+380685230547" class="btn btn-call btn-sm" onclick="event.stopPropagation()">
              <i class="bi bi-telephone-fill"></i> Зателефонувати
            </a>
            <button class="btn btn-details btn-sm" onclick="openModal(${item.id}); event.stopPropagation()">
              Характеристики
            </button>
          </div>
        </div>
      </div>
    `;

    card.querySelector(".product-card").addEventListener("click", () => openModal(item.id));
    card.querySelector(".product-card").addEventListener("keydown", e => {
      if (e.key === "Enter" || e.key === " ") openModal(item.id);
    });

    container.appendChild(card);
  });
}

function categoryLabel(cat) {
  const map = {
    tractor: "Трактор",
    attachments: "Ґрунтофреза",
    cultivator: "Ґрунтофреза",
    parts: "Запчастини"
  };
  return map[normalizeFilter(cat)] || cat;
}

function normalizeFilter(value) {
  const aliases = { cultivator: "attachments" };
  return aliases[value] || value;
}

// =============================================
// ФІЛЬТРИ
// =============================================
function initFilters() {
  document.querySelectorAll(".filter-btn").forEach(btn => {
    btn.addEventListener("click", function () {
      document.querySelectorAll(".filter-btn").forEach(b => b.classList.remove("active"));
      this.classList.add("active");
      renderCards(normalizeFilter(this.dataset.filter));
    });
  });
}

// =============================================
// МОДАЛЬНЕ ВІКНО
// =============================================
function openModal(id) {
  const item = catalog.find(c => c.id === id);
  if (!item) return;

  const modalImg = document.getElementById("modal-img");
  document.getElementById("modal-title").textContent = item.name;
  modalImg.style.opacity = "1";
  modalImg.style.filter = "none";
  modalImg.src = item.image;
  modalImg.alt = item.name;

  const tbody = document.getElementById("modal-specs-body");
  tbody.innerHTML = item.specs.map(s => `
    <tr>
      <td class="spec-num">${s.num}</td>
      <td class="spec-name">${s.name}</td>
      <td class="spec-value">${s.value}</td>
    </tr>
  `).join("");

  const noteEl = document.getElementById("modal-note");
  if (item.note) {
    noteEl.textContent = item.note;
    noteEl.style.display = "block";
  } else {
    noteEl.style.display = "none";
  }

  const modal = new bootstrap.Modal(document.getElementById("productModal"));
  modal.show();
}

// =============================================
// STICKY HEADER
// =============================================
function initScrollHeader() {
  const header = document.getElementById("main-header");
  window.addEventListener("scroll", () => {
    header.classList.toggle("scrolled", window.scrollY > 40);
  }, { passive: true });
}

// =============================================
// SMOOTH SCROLL
// =============================================
function initSmoothScroll() {
  document.querySelectorAll('a[href^="#"]').forEach(a => {
    a.addEventListener("click", e => {
      const target = document.querySelector(a.getAttribute("href"));
      if (target) {
        e.preventDefault();
        target.scrollIntoView({ behavior: "smooth", block: "start" });
      }
    });
  });
}

// =============================================
// INIT
// =============================================
document.addEventListener("DOMContentLoaded", () => {
  renderCards("all");
  initFilters();
  initScrollHeader();
  initSmoothScroll();
});
